# Tries seeds for drawers 16-50 and the 5 hideouts until each one passes validate.check + blocks_ok.
# Writes levelseeds.py. Run: python3 findseeds.py
import io, contextlib, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import levels as LV
import validate as VA

def ok(l):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        good = VA.check(l) and VA.blocks_ok(l)
    return good

seeds, hseeds = {}, {}
for (num, name, bg, music, (crew, old), boss) in LV.NEW:
    for sd in range(num * 1000, num * 1000 + 400):
        if ok(LV.gen_level(num, name, bg, music, sd, crew, old, boss)): seeds[num] = sd; break
    else: raise SystemExit('no seed for %d' % num)
    print(num, name, seeds[num], flush=True)
for k, (name, boss, src, (crew, old)) in enumerate(LV.HIDEOUTS):
    for sd in range(90000 + k * 1000, 90000 + k * 1000 + 400):
        if ok(LV.gen_level(60 + k, name, 'hideout', 'grand', sd, crew, old, boss, width=170, hideout=True)): hseeds[k] = sd; break
    else: raise SystemExit('no seed for hideout %d' % k)
    print('hideout', k, name, hseeds[k], flush=True)
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'levelseeds.py'), 'w').write(
    '# generated by findseeds.py: one seed per generated drawer that passes validate.py\nSEEDS = %r\nHSEEDS = %r\n' % (seeds, hseeds))
